def test_symlink_roots_and_markers_are_never_followed(tmp_path):
    root = owned(tmp_path / "real")
    link = tmp_path / "link"
    try:
        link.symlink_to(root, target_is_directory=True)
    except OSError:
        pytest.skip("symlink creation requires privileges on this host")
    marker_link = tmp_path / "marker-link"
    marker_link.mkdir()
    (marker_link / ".hydraweave-root").symlink_to(root / ".hydraweave-root")
    uninstall.remove(roots=[link, marker_link], home=tmp_path, dry_run=False)
    assert root.exists() and link.is_symlink() and marker_link.exists()


