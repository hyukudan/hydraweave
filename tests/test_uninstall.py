def test_dry_run_lists_units_without_mutations(tmp_path):
    units = tmp_path / "units"
    units.mkdir()
    names = ["hydraweave-node.service", "hydraweave-portal.service", "hydraweave-ui.service",
             "hl-model1.service", "hydraweave-model2.service"]
    for name in names:
        (units / name).write_text("# Generated by hydraweave-node\n")
    (units / "hl-unrelated.service").write_text("Description=Another application\n")
    (units / "other.service").write_text("Description=Other application\n")
    root = owned(tmp_path / "root")
    runner = Mock()
    plan = uninstall.remove(roots=[root], unit_dirs=[units], home=tmp_path, runner=runner)
    assert {row["unit"] for row in plan["actions"] if row["action"] == "stop-disable"} == set(names)
    runner.assert_not_called()
    assert root.exists()
    uninstall.remove(roots=[root], unit_dirs=[units], home=tmp_path, runner=runner, dry_run=False)
    commands = [call.args[0] for call in runner.call_args_list]
    assert all(["systemctl", "--user", operation, name] in commands
               for name in names for operation in ("stop", "disable"))
    assert commands[-1] == ["systemctl", "--user", "daemon-reload"]
    assert not root.exists() and (units / "hl-unrelated.service").exists()


def test_failed_stop_keeps_units_and_data(tmp_path):
    units = tmp_path / "units"
    units.mkdir()
    unit = units / "hydraweave-node.service"
    unit.touch()
    root = owned(tmp_path / "root")
