def owned(path, marker=".hydraweave-root"):
    path.mkdir(parents=True, exist_ok=True)
    (path / marker).touch()
    return path


def test_remove_only_marked_roots_and_report_kept_bytes(tmp_path):
    root = owned(tmp_path / "owned")
    unmarked = tmp_path / "unmarked"
    unmarked.mkdir()
    (unmarked / "file").write_bytes(b"1234")
    config = owned(tmp_path / "config")
    models = owned(tmp_path / "models", ".hydraweave-assets")
    (models / "part.gguf").write_bytes(b"model")
    runner = Mock()
    result = uninstall.remove(roots=[root, unmarked], configs=[config], models=[models],
                              home=tmp_path, dry_run=False, runner=runner)
    assert not root.exists()
    assert config.exists() and models.exists() and unmarked.exists()
    kept = {Path(row["path"]): row for row in result["actions"] if row["action"] == "keep"}
    assert kept[models]["bytes"] == 5
    assert kept[unmarked]["bytes"] == 4
    runner.assert_not_called()


